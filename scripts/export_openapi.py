"""Refresh implemented routes while retaining SDD notes on planned capabilities."""

from pathlib import Path

import yaml
from cmp_api.main import app

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "contracts" / "openapi.yaml"
generated = app.openapi()
if OUTPUT.exists():
    existing = yaml.safe_load(OUTPUT.read_text(encoding="utf-8")) or {}
    description = existing.get("info", {}).get("description")
    if description:
        generated["info"]["description"] = description
    for key, value in existing.items():
        if key.startswith("x-sdd-"):
            generated[key] = value
OUTPUT.write_text(
    "# Generated by `make openapi`; x-sdd-* notes and info.description are preserved.\n"
    + yaml.safe_dump(generated, allow_unicode=True, sort_keys=False),
    encoding="utf-8",
)
print(OUTPUT)
