#!/usr/bin/env bash
# Create or complete demo host secrets without overwriting existing values (ticket 21, #100).
#   ensure-secrets.sh <env-file> <secrets-dir> [connections-dir]
# - <env-file>: generated keys are appended only when missing (redeploys keep existing keys).
# - <secrets-dir>/aws/config: named profiles backed by the EC2 instance role (no static keys):
#   Provisioning (optionally assuming PROVISIONING_AWS_ROLE_ARN) and cmp-demo-build (ticket 28,
#   also the connection principal: generated `cmp-conn-*` profiles use it as source_profile).
# - [connections-dir]/config: the API-owned generated connection config (ticket 46), shared with
#   the worker. Holds no key. Seeded from aws/config only when missing; the API rewrites it.
# - <secrets-dir>/gcp/: operator places key.json here out of band; this script never creates it.
# - <secrets-dir>/sandbox/: operator places the k3d-cmp-sandbox kubeconfig here (ticket 45); only
#   the empty directory is created so the worker's read-only mount always exists.
# - ENV_FILE_ENCRYPTION_KEY (ticket 45, N12): base64url 32 bytes for the `.env` upload store. Kept
#   forever once written: a different key makes every stored upload unreadable.
set -euo pipefail

env_file="${1:?env file required}"
secrets_dir="${2:?secrets directory required}"
connections_dir="${3:-}"
umask 077

touch "$env_file"
chmod 600 "$env_file"
ensure_key() {
  local name="$1" bytes="$2"
  if ! grep -q "^${name}=" "$env_file"; then
    printf '%s=%s\n' "$name" "$(openssl rand -hex "$bytes")" >>"$env_file"
  fi
}
ensure_key PLATFORM_DB_PASSWORD 24
ensure_key TEMPORAL_DB_PASSWORD 24
ensure_key AGENT_ENROLLMENT_ADMIN_KEY 32
ensure_key APPROVAL_ADMIN_KEY 32
ensure_key WEB_AUTH_SECRET 32
if ! grep -q "^ENV_FILE_ENCRYPTION_KEY=" "$env_file"; then
  printf 'ENV_FILE_ENCRYPTION_KEY=%s\n' \
    "$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '=\n')" >>"$env_file"
fi

env_value() {
  sed -n "s/^$1=//p" "$env_file" | tail -n 1
}

install -d -m 700 "$secrets_dir" "$secrets_dir/aws" "$secrets_dir/gcp" "$secrets_dir/sandbox"
profile="$(env_value PROVISIONING_AWS_PROFILE)"
profile="${profile:-cmp-demo-provisioning}"
region="$(env_value PROVISIONING_AWS_REGION)"
region="${region:-ap-northeast-2}"
role_arn="$(env_value PROVISIONING_AWS_ROLE_ARN)"
aws_config="$secrets_dir/aws/config"
{
  printf '# Generated by infra/demo/ensure-secrets.sh. No static credentials.\n'
  printf '[profile %s]\n' "$profile"
  if [[ -n "$role_arn" ]]; then
    printf 'role_arn = %s\n' "$role_arn"
    printf 'role_session_name = cmp-demo-worker\n'
  fi
  printf 'credential_source = Ec2InstanceMetadata\n'
  printf 'region = %s\n' "$region"
  # Ticket 28 (#152): the Build module (S3 sources/tests/builds, platform ECR) always uses the
  # instance role itself, never PROVISIONING_AWS_ROLE_ARN.
  printf '[profile cmp-demo-build]\n'
  printf 'credential_source = Ec2InstanceMetadata\n'
  printf 'region = %s\n' "$region"
} >"$aws_config.tmp"
mv "$aws_config.tmp" "$aws_config"
chmod 600 "$aws_config"
if [[ -n "$connections_dir" ]]; then
  install -d -m 700 "$connections_dir"
  if [[ ! -f "$connections_dir/config" ]]; then
    install -m 640 "$aws_config" "$connections_dir/config"
  fi
fi
if [[ -f "$secrets_dir/gcp/key.json" ]]; then
  chmod 600 "$secrets_dir/gcp/key.json"
fi
