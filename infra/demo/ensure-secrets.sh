#!/usr/bin/env bash
# Create or complete demo host secrets without overwriting existing values (ticket 21, #100).
#   ensure-secrets.sh <env-file> <secrets-dir>
# - <env-file>: generated keys are appended only when missing (redeploys keep existing keys).
# - <secrets-dir>/aws/config: named profile backed by the EC2 instance role (no static keys).
# - <secrets-dir>/gcp/: operator places key.json here out of band; this script never creates it.
set -euo pipefail

env_file="${1:?env file required}"
secrets_dir="${2:?secrets directory required}"
umask 077

touch "$env_file"
chmod 600 "$env_file"
ensure_key() {
  local name="$1" bytes="$2"
  if ! grep -q "^${name}=" "$env_file"; then
    printf '%s=%s\n' "$name" "$(openssl rand -hex "$bytes")" >>"$env_file"
  fi
}
ensure_key PLATFORM_DB_PASSWORD 24
ensure_key TEMPORAL_DB_PASSWORD 24
ensure_key AGENT_ENROLLMENT_ADMIN_KEY 32
ensure_key APPROVAL_ADMIN_KEY 32
ensure_key WEB_AUTH_SECRET 32

env_value() {
  sed -n "s/^$1=//p" "$env_file" | tail -n 1
}

install -d -m 700 "$secrets_dir" "$secrets_dir/aws" "$secrets_dir/gcp"
profile="$(env_value PROVISIONING_AWS_PROFILE)"
profile="${profile:-cmp-demo-provisioning}"
region="$(env_value PROVISIONING_AWS_REGION)"
region="${region:-ap-northeast-2}"
role_arn="$(env_value PROVISIONING_AWS_ROLE_ARN)"
aws_config="$secrets_dir/aws/config"
{
  printf '# Generated by infra/demo/ensure-secrets.sh. No static credentials.\n'
  printf '[profile %s]\n' "$profile"
  if [[ -n "$role_arn" ]]; then
    printf 'role_arn = %s\n' "$role_arn"
    printf 'role_session_name = cmp-demo-worker\n'
  fi
  printf 'credential_source = Ec2InstanceMetadata\n'
  printf 'region = %s\n' "$region"
} >"$aws_config.tmp"
mv "$aws_config.tmp" "$aws_config"
chmod 600 "$aws_config"
if [[ -f "$secrets_dir/gcp/key.json" ]]; then
  chmod 600 "$secrets_dir/gcp/key.json"
fi
